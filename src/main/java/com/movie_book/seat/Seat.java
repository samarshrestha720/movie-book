package com.movie_book.seat;

/**
 *
 * @author Dr. PANDA 002
 */
public class Seat {

    private Long id;
    private String number;
    private String status; // can be "available", "booked", or "processing"
    private Long showId;
    private Long ticketId; // assuming this is nullable if a seat can exist without a ticket

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getNumber() {
        return number;
    }

    public void setNumber(String number) {
        this.number = number;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public Long getShowId() {
        return showId;
    }

    public void setShowId(Long showId) {
        this.showId = showId;
    }

    public Long getTicketId() {
        return ticketId;
    }

    public void setTicketId(Long ticketId) {
        this.ticketId = ticketId;
    }

}
